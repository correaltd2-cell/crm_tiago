-- PRODUTOS -----------------------------------------------------
-- Tabela única: linha de produto + código do talão + preços das
-- duas tabelas + unidades por placa P/G. Nada disso é digitado
-- pelo vendedor — tudo vem do cadastro (editável no Admin).
create table if not exists produtos (
  id uuid primary key default gen_random_uuid(),
  codigo text not null,
  nome text not null,
  variacao text,                    -- ex.: Classic / M. Encantado / Prata / Dourado
  linha text,                       -- linha de produto (upsell + ranking)
  preco_simples numeric,            -- Tabela Simples   (null = preço a cadastrar)
  preco_lucro numeric,              -- Lucro Presumido  (null = preço a cadastrar)
  unid_placa_p int not null,        -- unidades na placa Pequena
  unid_placa_g int not null,        -- unidades na placa Grande
  ativo boolean not null default true,
  created_at timestamptz not null default now()
);

create unique index if not exists uq_produtos_codigo_variacao
  on produtos (codigo, coalesce(variacao, ''));

